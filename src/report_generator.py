from datetime import datetime
from pathlib import Path
import re


APP_ROOT = Path(__file__).resolve().parent.parent

CLASS_LABELS = {
    "normal": "Normal",
    "immature": "Immature Cataract",
    "mature": "Mature Cataract",
    "inconclusive": "Inconclusive"
}


def generate_report(result, image_name="Uploaded image", save=True):
    """
    Generate a research-oriented Markdown inference report.

    Parameters
    ----------
    result : dict
        Output from NetraScanInference.predict().
    image_name : str
        Original image filename or identifier.
    save : bool
        Whether to save the report to the portable reports folder.

    Returns
    -------
    dict
        Report text and optional saved file path.
    """

    timestamp = datetime.now().astimezone()

    ensemble = result["ensemble_prediction"]
    agreement = result["agreement"]
    predictions = result["predictions"]

    ensemble_label = CLASS_LABELS.get(
        ensemble, str(ensemble).title()
    )

    lines = [
        "# NetraScan.AI — Cataract Classification Report",
        "",
        f"**Generated:** {timestamp.strftime('%d %B %Y, %I:%M:%S %p %Z')}",
        f"**Input image:** {Path(str(image_name)).name}",
        "**System:** Multi-Transformer Cataract Classification",
        "",
        "---",
        "",
        "## 1. Ensemble Classification",
        "",
        f"**Predicted category:** {ensemble_label}",
        f"**Model agreement:** {agreement}",
        "",
        "The ensemble decision is determined by majority voting "
        "across three independently trained transformer architectures.",
        "",
        "## 2. Individual Model Predictions",
        "",
        "| Architecture | Prediction | Confidence | Inference Time |",
        "|---|---|---:|---:|"
    ]

    for model_name, details in predictions.items():

        prediction = CLASS_LABELS.get(
            details["predicted_class"],
            str(details["predicted_class"]).title()
        )

        confidence = details["confidence"] * 100
        latency = details["inference_ms"]

        lines.append(
            f"| {model_name} | {prediction} | "
            f"{confidence:.2f}% | {latency:.2f} ms |"
        )

    lines.extend([
        "",
        "## 3. Model Architecture Summary",
        "",
        "- **ViT-B/16:** Vision Transformer using global "
        "self-attention over image patches.",
        "- **Swin-Tiny:** Hierarchical Vision Transformer "
        "using shifted-window attention.",
        "- **MobileViT-S:** Lightweight hybrid architecture "
        "combining convolutional operations with transformer blocks.",
        "",
        "## 4. Explainable AI — Grad-CAM",
        "",
        "The system supports Grad-CAM visualization using "
        "the Swin-Tiny Stage 2 feature representation.",
        "",
        "Warmer heatmap regions indicate image locations "
        "associated with stronger class-related model activations. "
        "These visualizations are not validated clinical "
        "localizations and may include irrelevant image regions.",
        "",
        "## 5. Interpretation",
        ""
    ])

    vote_count = int(str(agreement).split("/")[0])

    if ensemble == "inconclusive" or vote_count < 2:

        lines.append(
            "The three models did not establish a majority "
            "classification. The output is inconclusive."
        )

    elif vote_count == 3:

        lines.append(
            f"All three architectures predicted "
            f"**{ensemble_label}**. This represents unanimous "
            "model agreement for the supplied image, but does "
            "not establish clinical certainty."
        )

    else:

        lines.append(
            f"Two of the three architectures predicted "
            f"**{ensemble_label}**. One model disagreed, "
            "indicating inter-model prediction variability."
        )

    lines.extend([
        "",
        "## 6. Research Limitations",
        "",
        "- Performance on new cameras, lighting conditions, "
        "populations, and acquisition devices has not been "
        "established by this individual inference.",
        "- Model confidence is not equivalent to a calibrated "
        "probability of disease.",
        "- Grad-CAM does not independently verify clinical correctness.",
        "- The system cannot replace ophthalmic examination.",
        "",
        "## 7. Disclaimer",
        "",
        "**NetraScan.AI is an academic research prototype.** "
        "Its predictions and visual explanations are intended "
        "for demonstration and research only. They must not "
        "be used for clinical diagnosis, treatment decisions, "
        "or medical triage.",
        "",
        "---",
        "",
        "*Generated by the NetraScan.AI offline reporting engine.*"
    ])

    report_text = "\n".join(lines)

    saved_path = None

    if save:

        output_dir = APP_ROOT / "reports"
        output_dir.mkdir(parents=True, exist_ok=True)

        safe_name = re.sub(
            r"[^A-Za-z0-9_-]+",
            "_",
            Path(str(image_name)).stem
        ).strip("_")[:50] or "image"

        filename = (
            f"NetraScan_{safe_name}_"
            f"{timestamp.strftime('%Y%m%d_%H%M%S_%f')}.md"
        )

        saved_path = output_dir / filename

        saved_path.write_text(
            report_text,
            encoding="utf-8"
        )

    return {
        "text": report_text,
        "path": str(saved_path) if saved_path else None
    }
